import XCTest
@testable import Nursery

/// The picture size from an H.264 SPS. The real SPSs come from x264 (ffmpeg), and ffprobe
/// confirmed each size. The two made ones were checked with ffmpeg's trace_headers.
final class SPSTests: XCTestCase {
    private func size(_ bytes: [UInt8]) -> [Int]? {
        H264SPS.size(bytes).map { [$0.width, $0.height] }
    }

    // Baseline, 640 × 368 cropped to 360.
    func testBaseline360() {
        let sps: [UInt8] = [0x67, 0x42, 0xC0, 0x16, 0xD9, 0x00, 0xA0, 0x2F, 0xF9, 0x70, 0x11, 0x00, 0x00, 0x03, 0x00,
                            0x01, 0x00, 0x00, 0x03, 0x00, 0x02, 0x0F, 0x16, 0x2E, 0x48]
        XCTAssertEqual(size(sps), [640, 360])
    }

    // High, 1920 × 1088 cropped to 1080.
    func testHigh1080() {
        let sps: [UInt8] = [0x67, 0x64, 0x00, 0x28, 0xAC, 0xD9, 0x40, 0x78, 0x02, 0x27, 0xE5, 0xC0, 0x44, 0x00, 0x00,
                            0x03, 0x00, 0x04, 0x00, 0x00, 0x03, 0x00, 0x08, 0x3C, 0x60, 0xC6, 0x58]
        XCTAssertEqual(size(sps), [1920, 1080])
    }

    // Main, 2560 × 1440, no cropping.
    func testMain1440() {
        let sps: [UInt8] = [0x67, 0x4D, 0x40, 0x32, 0xEC, 0xA0, 0x14, 0x00, 0x5A, 0xD8, 0x08, 0x80, 0x00, 0x00, 0x03,
                            0x00, 0x80, 0x00, 0x00, 0x03, 0x01, 0x07, 0x8C, 0x18, 0xCB]
        XCTAssertEqual(size(sps), [2560, 1440])
    }

    // The go2rtc SPS of SDPTests (a Tapo stream): 1280 × 720.
    func testGo2rtc720() {
        let sps: [UInt8] = [0x67, 0x64, 0x00, 0x1F, 0xAC, 0xD9, 0x40, 0x50, 0x05, 0xBB, 0x01, 0x10, 0x00,
                            0x00, 0x03, 0x00, 0x10, 0x00, 0x00, 0x03, 0x03, 0x28, 0xF1, 0x83, 0x19, 0x60]
        XCTAssertEqual(size(sps), [1280, 720])
    }

    // The often quoted "Z0IAKeKQFAe2AtwEBAaQeJEV": 40 × 30 macroblocks, so 640 × 480.
    func testBase64Baseline480() throws {
        let data = try XCTUnwrap(Data(base64Encoded: "Z0IAKeKQFAe2AtwEBAaQeJEV"))
        XCTAssertEqual(size([UInt8](data)), [640, 480])
    }

    // Interlaced (fields): the height counts two fields.
    func testInterlaced576() {
        let sps: [UInt8] = [0x67, 0x64, 0x00, 0x16, 0xAC, 0xD9, 0x40, 0xB4, 0x24, 0xD8, 0x08, 0x80, 0x00, 0x00, 0x03,
                            0x00, 0x80, 0x00, 0x00, 0x03, 0x01, 0x0F, 0x8A, 0x14, 0xCB]
        XCTAssertEqual(size(sps), [720, 576])
    }

    // High 4:4:4: the chroma format field is 3.
    func testHigh444() {
        let sps: [UInt8] = [0x67, 0xF4, 0x00, 0x1F, 0x91, 0x9B, 0x28, 0x0A, 0x00, 0xB7, 0x60, 0x22, 0x00, 0x00, 0x03,
                            0x00, 0x02, 0x00, 0x00, 0x03, 0x00, 0x04, 0x1E, 0x30, 0x63, 0x2C]
        XCTAssertEqual(size(sps), [1280, 720])
    }

    // High 4:2:2, 1376 cropped on the right to 1366: the crop unit is 2 pixels.
    func testHigh422RightCrop() {
        let sps: [UInt8] = [0x67, 0x7A, 0x00, 0x20, 0xBC, 0xD9, 0x40, 0x56, 0x06, 0x1E, 0x6F, 0x01, 0x10, 0x00, 0x00,
                            0x03, 0x00, 0x10, 0x00, 0x00, 0x03, 0x00, 0x20, 0xF1, 0x83, 0x19, 0x60]
        XCTAssertEqual(size(sps), [1366, 768])
    }

    // Made: a scaling matrix (a full 4×4 list and a short 8×8 list) and pic_order_cnt_type 1.
    func testScalingListsAndPOCType1() {
        let sps: [UInt8] = [0x67, 0x64, 0x00, 0x28, 0xAD, 0x94, 0xC5, 0x31, 0x4C, 0x53, 0x14, 0xC5, 0x31, 0x4C,
                            0x53, 0x02, 0x28, 0xE1, 0x55, 0x0A, 0x98, 0x81, 0xE4, 0x01, 0xE0, 0x08, 0x9F, 0x95]
        XCTAssertEqual(size(sps), [1920, 1080])
    }

    // Made: a big offset puts 00 00 00 in the bits, so the SPS has two emulation prevention bytes.
    func testEmulationPreventionBytes() {
        let sps: [UInt8] = [0x67, 0x4D, 0x00, 0x1E, 0xD3, 0x40, 0x00, 0x00, 0x03, 0x00, 0x40, 0x00, 0x00, 0x03,
                            0x01, 0x40, 0x50, 0x17, 0xFC, 0xA8]
        XCTAssertEqual(size(sps), [640, 360])
    }

    func testGarbageIsNil() {
        XCTAssertNil(H264SPS.size([]))
        XCTAssertNil(H264SPS.size([0x67]))
        XCTAssertNil(H264SPS.size([0x68, 0xEB, 0xE3, 0xCB, 0x22, 0xC0]))        // A PPS, not an SPS.
        XCTAssertNil(H264SPS.size([0x67, 0x64, 0x00, 0x1F, 0xAC]))              // Cut off.
        XCTAssertNil(H264SPS.size([0x67, 0x42, 0x00, 0x1E, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]))   // Only zeros.
    }
}
